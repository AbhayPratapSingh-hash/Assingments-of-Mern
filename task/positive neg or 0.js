//Positive, Negative, or Zero
// Check if a given number is positive, negative, or zero.

let number = -10; 

if (number > 0) {
  console.log(`${number} is a positive number.`);
} else if (number < 0) {
  console.log(`${number} is a negative number.`);
} else {
  console.log(`${number} is zero.`);
}